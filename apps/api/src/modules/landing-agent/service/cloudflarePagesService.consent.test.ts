// @vitest-environment jsdom
import { createHash } from "node:crypto";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import type { LeadFormConfig } from "../leadFormConfig";
import { encodeLeadFormMarkerId } from "../leadFormConfig";
import { replaceLeadFormMarkers } from "../leadFormHtml";
import { buildLeadFormScript } from "./cloudflarePagesService";
import { consentModeOf } from "../leadConsent";

const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const TEXT = "I agree to be contacted about my enquiry.";
const email = { key: "email", label: "Work email", type: "email", required: true };
const requiredConfig = { fields: [email], buttonLabel: "Send", successMessage: "Thanks", consent: { enabled: true, required: true, text: TEXT } } as LeadFormConfig;
const optionalConfig = { fields: [email], buttonLabel: "Send", successMessage: "Thanks", consent: { enabled: true, required: false, text: TEXT } } as LeadFormConfig;
const plainConfig = { fields: [email], buttonLabel: "Send", successMessage: "Thanks" } as LeadFormConfig;

// The Worker's inline script for pages without a consent block is unchanged, so their stored HTML and CSP hash stay the same.
// The script embeds Date.now() as its version, so the clock is pinned. The hashes are those of the script before this change.
describe("Worker lead script for pages without consent is unchanged", () => {
    beforeEach(() => {
        vi.spyOn(Date, "now").mockReturnValue(1793528250004);
    });

    afterEach(() => {
        vi.restoreAllMocks();
    });

    it("the script hashes as before (no Meta Pixel)", () => {
        expect(sha(buildLeadFormScript("guide"))).toBe("0365894d54f11f33bc10f6166094f9ab0aec37241d0ff5de70d5d14704eb15e3");
    });

    it("the script hashes as before (with a Meta Pixel)", () => {
        expect(sha(buildLeadFormScript("guide", true))).toBe("a10e39a94b49a5090a7252b0a984c0e1b52a9d59e060f867bc1bccf77b6af2f0");
    });
});

// The lead form script is generated by the API and runs in the browser on the connected domain.
// These tests run the consent part of it in jsdom against the server-rendered form markup.
describe("Worker lead script enforces the consent box", () => {
    let fetchMock: ReturnType<typeof vi.fn>;

    function mountPage(config: LeadFormConfig, consentTicked: boolean) {
        document.body.innerHTML = replaceLeadFormMarkers(`<section><div class="cmf-form" id="${encodeLeadFormMarkerId(config)}"></div></section>`, { slug: "guide" });
        const box = document.querySelector<HTMLInputElement>('input[name="cmfConsent"]');
        if (box) box.checked = consentTicked;
        const emailInput = document.querySelector<HTMLInputElement>('input[name="email"]');
        if (emailInput) emailInput.value = "ada@example.com";
        new Function(buildLeadFormScript("guide", false, consentModeOf(config.consent)))();
        return document.getElementById("la-lead-form") as HTMLFormElement;
    }

    async function submitForm(form: HTMLFormElement) {
        form.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
        await new Promise((resolve) => setTimeout(resolve, 0));
    }

    beforeEach(() => {
        fetchMock = vi.fn(async () => ({ ok: true }));
        vi.stubGlobal("fetch", fetchMock);
    });

    afterEach(() => {
        vi.unstubAllGlobals();
        document.body.innerHTML = "";
    });

    it("blocks a required, unticked submit with a message and sends nothing", async () => {
        const form = mountPage(requiredConfig, false);
        await submitForm(form);
        const leadCalls = fetchMock.mock.calls.filter(([url]) => String(url).endsWith("/guide/lead"));
        expect(leadCalls).toHaveLength(0);
        expect(document.getElementById("la-consent-error")?.textContent).toMatch(/tick/i);
    });

    it("sends a ticked consent as a top-level flag and leaves it out of the form fields", async () => {
        const form = mountPage(requiredConfig, true);
        await submitForm(form);
        const leadCall = fetchMock.mock.calls.find(([url]) => String(url).endsWith("/guide/lead"));
        expect(leadCall).toBeDefined();
        const body = JSON.parse(String((leadCall![1] as RequestInit).body));
        expect(body.consent).toBe(true);
        expect(body.formFields).not.toHaveProperty("cmfConsent");
    });

    it("sends an unticked optional consent as false instead of blocking", async () => {
        const form = mountPage(optionalConfig, false);
        await submitForm(form);
        const leadCall = fetchMock.mock.calls.find(([url]) => String(url).endsWith("/guide/lead"));
        expect(leadCall).toBeDefined();
        expect(JSON.parse(String((leadCall![1] as RequestInit).body)).consent).toBe(false);
    });

    it("the consent box starts unticked", () => {
        mountPage(requiredConfig, false);
        expect(document.querySelector<HTMLInputElement>('input[name="cmfConsent"]')?.checked).toBe(false);
    });

    it("pages without consent do not add the consent check", () => {
        expect(buildLeadFormScript("guide")).not.toContain("cmfConsent");
        expect(buildLeadFormScript("guide", false, "required")).toContain("cmfConsent");
    });
});
